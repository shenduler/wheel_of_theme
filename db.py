def get_all_topics():
    """Возвращает все темы из БД"""
    conn = get_connection()
    cursor = conn.execute('SELECT * FROM topics ORDER BY id')
    topics = [dict(row) for row in cursor.fetchall()]
    conn.close()
    return topics

def get_random_topic():
    """Возвращает случайную тему и обновляет статистику"""
    conn = get_connection()
    cursor = conn.execute('SELECT * FROM topics ORDER BY RANDOM() LIMIT 1')
    topic = dict(cursor.fetchone())

    # Обновляем статистику
    conn.execute('''
        UPDATE topics 
        SET times_rolled = times_rolled + 1, 
            last_rolled = datetime('now', 'localtime')
        WHERE id = ?
    ''', (topic['id'],))
    conn.commit()
    conn.close()
    return topic

def get_topics_count():
    """Возвращает количество тем в базе"""
    conn = get_connection()
    cursor = conn.execute('SELECT COUNT(*) as count FROM topics')
    count = cursor.fetchone()['count']
    conn.close()
    return count